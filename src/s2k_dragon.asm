; S2000 boot dragon (port of the GP-16 Rosetta OS dragon, art = art/dragon_frames.bin).
; Runs at OS entry BEFORE init: the hook is 0FE4:0002 `ljmp 1F50:0000` -> `ljmp DRAGON_SEG:0000`.
; It lives in the leftover load.asm object junk at the top of the image (no refs, reused as RAM later),
; which is safe because nothing has run yet but the 0x50 entry stub; the OS's own "load OS" path
; (2BD5:0000) copies a fresh image before re-entering, so the code is always intact when it runs.
;
; Entry state (from 0000:0053): DS=ES=SS=0, SP=0x300, IF=0, DF=0. We leave exactly that and
; continue to 1F50:0000. LCD = HD44780 16x2, port 0x62 cmd/busy, 0x60 data (same access pattern
; as the OS: busy poll, push/pop settle, out). Line 1 = DDRAM 0x80, line 2 = 0xC0.
; Borrows CGRAM chars 1-3 (read back first, restored at the end).
        cpu 186
        bits 16
        org 0

LCD_CMD   equ 0x62
LCD_DAT   equ 0x60
COLS      equ 16
POS0      equ -2
POSEND    equ 18
DOT       equ '.'
%ifndef DLY_OUTER
DLY_OUTER equ 4               ; one unit ~29 ms/step on hw; 1 = way too fast, 4 picked (2026-10-13)
%endif
%ifndef HOLD_STEPS
HOLD_STEPS equ 9              ; banner hold, ~1 s at DLY_OUTER 4
%endif
STACK_TOP equ 0x0800          ; private stack inside our segment (code+data well below this)

start:
        mov ax, cs
        mov ss, ax
        mov sp, STACK_TOP
        mov ds, ax
        mov es, ax
        cld

        ; save CGRAM chars 1-3 (addresses 8..31)
        mov al, 0x48
        call lcd_cmd
        mov di, saved
        mov cx, 24
.sv:    call lcd_rd
        stosb
        loop .sv

        ; banner
        mov al, 0x80
        mov si, line1
        call puts16
        mov al, 0xC0
        mov si, line2
        call puts16
        mov cx, HOLD_STEPS
.hold:  call delay
        loop .hold

        mov word [step], 0
        mov byte [laddr], 0x80
        mov word [text], line1
        call fly
        mov byte [laddr], 0xC0
        mov word [text], line2
        call fly

        ; restore CGRAM chars 1-3
        mov al, 0x48
        call lcd_cmd
        mov si, saved
        mov cx, 24
.rs:    lodsb
        call lcd_dat
        loop .rs

        ; back to the exact entry state, continue stock boot
        xor ax, ax
        mov ds, ax
        mov es, ax
        mov ss, ax
        mov sp, 0x0300
        jmp 0x1F50:0x0000

; fly one line: pos POS0..POSEND-1, 8-frame cycle continues across lines
fly:
        mov word [pos], POS0
.f:     mov ax, [step]
        and ax, 7
        call load_frame
        call drawrow
        call delay
        inc word [step]
        inc word [pos]
        cmp word [pos], POSEND
        jl .f
        ret

; drawrow: dragon cells (codes 1..3) at pos..pos+2, dots behind, text ahead
drawrow:
        mov al, [laddr]
        call lcd_cmd
        xor di, di
.col:   mov ax, di
        sub ax, [pos]
        cmp ax, 0
        jl .behind
        cmp ax, 2
        jg .ahead
        inc ax
        jmp .put
.behind:
        mov al, DOT
        jmp .put
.ahead: mov bx, [text]
        mov al, [bx+di]
.put:   call lcd_dat
        inc di
        cmp di, COLS
        jb .col
        ret

; load_frame(ax = 0..7): 24 CGRAM bytes for chars 1-3 (auto-increment from address 8)
load_frame:
        mov bx, 24
        mul bx
        mov si, ax
        add si, frames
        mov al, 0x48
        call lcd_cmd
        mov cx, 24
.lf:    lodsb
        call lcd_dat
        loop .lf
        ret

; puts16(al = DDRAM cmd, si = 16 chars)
puts16:
        call lcd_cmd
        mov cx, COLS
.p:     lodsb
        call lcd_dat
        loop .p
        ret

delay:
        push cx
        mov dx, DLY_OUTER
.o:     mov cx, 0xFFFF
.i:     loop .i
        dec dx
        jnz .o
        pop cx
        ret

; busy poll with timeout so a dead/absent LCD can never hang the boot
lcd_wait:
        push ax
        push cx
        mov cx, 0x4000
.w:     in al, LCD_CMD
        test al, 0x80
        loopnz .w
        pop cx
        pop ax
        ret

lcd_cmd:
        call lcd_wait
        push ax
        pop ax
        out LCD_CMD, al
        ret

lcd_dat:
        call lcd_wait
        push ax
        pop ax
        out LCD_DAT, al
        ret

lcd_rd:
        call lcd_wait
        push ax
        pop ax
        in al, LCD_DAT
        ret

%include "dragon_banner.inc"     ; line1/line2, 16 chars each (generated by mkbaby.py)

frames: incbin "dragon_frames.bin"   ; 8 frames x 3 chars x 8 rows

step:   dw 0
pos:    dw 0
text:   dw 0
laddr:  db 0
saved:  times 24 db 0
end_of_blob:
